import assert from 'node:assert/strict';
import { mkdtemp, readFile, mkdir, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import sharp from 'sharp';
import { createPlaygroundServer } from './server';
const dir = await mkdtemp(join(tmpdir(),'captured-test-'));
const vec = (axis: number) => Array.from({length:768},(_,i)=>i===axis?1:0);
let imageCalls = 0, queryCalls = 0;
const providerFactory = () => ({ image: async (bytes: Buffer) => { assert.equal((await sharp(bytes).metadata()).format,'jpeg'); return vec(imageCalls++); }, text: async (query: string) => { assert.equal(query,'unrelated to every filename'); queryCalls++; return vec(1); } });
let server = await createPlaygroundServer({ datasetDir:dir, providerFactory });
let token = '';
async function connectPage() { token = (await server.inject({url:'/',headers:{host:'localhost'}})).body.match(/name="playground-session" content="([^"]+)"/)![1]; }
const post = (url: string, payload: any = {}) => server.inject({method:'POST',url,headers:{host:'localhost','x-playground-session':token},payload});
const state = async () => (await server.inject({url:'/state',headers:{host:'localhost'}})).json();
await connectPage();
assert.equal((await server.inject({method:'POST',url:'/connect',headers:{host:'localhost'},payload:{key:'x'.repeat(24)}})).statusCode,403);
assert.equal((await server.inject({url:'/state',headers:{host:'evil.example'}})).statusCode,403);
assert.equal((await post('/search',{query:'test'})).statusCode,503);
const bytes = await sharp({create:{width:1500,height:1000,channels:3,background:'#ff0000'}}).png().toBuffer();
const upload = (bytes: Buffer) => server.inject({method:'POST',url:'/upload',headers:{host:'localhost','x-playground-session':token,'content-type':'application/octet-stream','x-file-name':'misleading-cat.jpg'},payload:bytes});
assert.equal((await upload(bytes)).statusCode,200);
assert.equal((await upload(bytes)).json().duplicate,true);
assert.equal((await upload(Buffer.from('not an image'))).statusCode,400);
await upload(await sharp({create:{width:400,height:400,channels:3,background:'#0000ff'}}).png().toBuffer());
assert.equal((await state()).total,2);
assert.equal((await post('/connect',{key:'test-only-key-never-real-123'})).statusCode,200);
assert.equal((await post('/index')).statusCode,202);
while ((await state()).indexing) await new Promise(r=>setTimeout(r,5));
assert.equal((await state()).indexed,2);
const results = (await post('/search',{query:'unrelated to every filename'})).json();
assert.equal(results.results[0].similarity,1);
assert.equal(results.results[1].similarity,0);
assert.equal((await post('/search',{query:'unrelated to every filename'})).json().cached,true);
assert.equal(queryCalls,1);
assert.equal(imageCalls,2);
assert.ok(!('description' in results.results[0]));
await server.close();
server = await createPlaygroundServer({datasetDir:dir,providerFactory});
await connectPage();
assert.equal((await state()).indexed,2);
assert.equal((await state()).configured,false);
await post('/connect',{key:'test-only-key-never-real-123'});
assert.equal((await post('/index')).json().indexing,false);
assert.equal(imageCalls,2);
const widths = await Promise.all((await state()).photos.map(async (p: any) => (await sharp(await readFile(join(dir,`${p.id}.jpg`))).metadata()).width));
assert.deepEqual(widths.sort(),[1024,400]);
await post('/disconnect');
assert.equal((await state()).indexed,2);
assert.ok(!(JSON.stringify(await state())).includes('test-only-key'));
await server.close();
console.log('PASS: uploads, duplicates, invalid images, request security, pixel-only ranking, query caching, restart persistence, key forgetting. Gemini provider mocked; no real API calls.');

const folderDir = await mkdtemp(join(tmpdir(),'captured-folders-'));
await mkdir(join(folderDir,'my-photos/nested'),{recursive:true});
await writeFile(join(folderDir,'my-photos/a.png'),bytes);
await writeFile(join(folderDir,'my-photos/nested/duplicate.png'),bytes);
await writeFile(join(folderDir,'my-photos/broken.jpg'),'not an image');
server = await createPlaygroundServer({datasetDir:folderDir,providerFactory});
await connectPage();
assert.equal((await state()).total,1);
assert.equal((await post('/scan')).json().added,0);
await writeFile(join(folderDir,'my-photos/new.png'),await sharp({create:{width:50,height:50,channels:3,background:'#abcdef'}}).png().toBuffer());
const scan = (await post('/scan')).json();
assert.equal(scan.added,1); assert.equal(scan.skipped.length,1);
await server.close();
server = await createPlaygroundServer({datasetDir:folderDir,providerFactory});
assert.equal((await state()).total,2);
await server.close();
console.log('PASS: recursive photo folders, deduplication, invalid-file handling, rescan and restart.');
