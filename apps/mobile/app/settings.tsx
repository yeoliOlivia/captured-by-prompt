import { useEffect, useState } from 'react';
import { Alert, KeyboardAvoidingView, Platform, ScrollView, StyleSheet, Text, TextInput, View } from 'react-native';
import Constants from 'expo-constants';
import { Ionicons } from '@expo/vector-icons';
import type { Health } from '@captured/core';
import { store } from '../src/store';
import { api } from '../src/api';
import { useLibrary } from '../src/library';
import { Button, Notice, styles as common } from '../src/components';
import { colors } from '../src/theme';

export default function Settings() {
  const library = useLibrary();
  const [url, setUrl] = useState('');
  const [token, setToken] = useState('');
  const [health, setHealth] = useState<Health | null>(null);
  const [message, setMessage] = useState('');
  const [checking, setChecking] = useState(false);
  useEffect(() => {
    Promise.all([store.setting('server-url'), store.token()]).then(([saved, secret]) => {
      const host = Constants.expoConfig?.hostUri?.split(':')[0] ?? '192.168.1.100';
      setUrl(saved ?? `http://${host}:8787`); setToken(secret);
    }).catch(() => setMessage('Could not load settings.'));
  }, []);
  const save = async () => {
    if (library.activity || checking) return;
    setChecking(true); setMessage(''); setHealth(null);
    try {
      const parsed = new URL(url.trim());
      if (!['http:', 'https:'].includes(parsed.protocol) || parsed.username || parsed.password || parsed.pathname !== '/' || parsed.search || parsed.hash) throw new Error('Enter only the server origin, for example http://192.168.1.20:8787.');
      if (token.trim().length < 32) throw new Error('Paste the development token generated by npm run token.');
      await store.setSetting('server-url', parsed.origin); await store.setToken(token.trim());
      const result = await api.health(); setHealth(result);
      setMessage(result.geminiReady ? 'Connected. Free-tier configuration is confirmed on the server.' : 'Connected. Complete the Gemini free-tier setup in the server .env before indexing.');
    } catch (error) { setMessage(error instanceof Error ? error.message : 'Could not connect.'); }
    finally { setChecking(false); }
  };
  const clear = () => Alert.alert('Delete this collection?', 'Remove imported copies, descriptions, embeddings, and saved searches from this app. Your camera-roll originals stay untouched.', [
    { text: 'Keep collection', style: 'cancel' }, { text: 'Delete local data', style: 'destructive', onPress: () => { void library.clear(); } },
  ]);

  return <KeyboardAvoidingView style={{ flex: 1, backgroundColor: colors.background }} behavior={Platform.OS === 'ios' ? 'padding' : undefined}><ScrollView contentContainerStyle={s.content} keyboardShouldPersistTaps="handled">
    <View style={s.card}><View style={s.row}><Ionicons name="leaf-outline" size={25} color={colors.green} /><Text style={s.title}>Small collection. Zero paid calls.</Text></View>
      <Text style={common.body}>30 selected photos, stored on your phone. This development build uses free quotas and verified promotional credits only.</Text>
      <Text style={s.footnote}>Free status is a setup confirmation, not an independent account audit. Keep Gemini billing off and TypeSafe auto-refills off. Paid mode is not implemented.</Text>
    </View>
    <Text style={common.label}>CONNECT YOUR MAC</Text>
    <Text style={common.body}>Keep the local API running and connect both devices to the same trusted Wi-Fi network.</Text>
    <Text style={s.fieldLabel}>Server address</Text>
    <TextInput accessibilityLabel="Local API server address" value={url} onChangeText={setUrl} autoCapitalize="none" autoCorrect={false} keyboardType="url" style={common.input} editable={!checking && !library.activity} />
    <Text style={s.fieldLabel}>Development token</Text>
    <TextInput accessibilityLabel="Development token" value={token} onChangeText={setToken} autoCapitalize="none" autoCorrect={false} secureTextEntry style={common.input} editable={!checking && !library.activity} placeholder="Paste DEV_TOKEN, not a model API key" />
    <Button label="Save & check connection" onPress={() => { void save(); }} busy={checking} disabled={Boolean(library.activity)} icon="link-outline" />
    {!!message && <Notice text={message} />}
    {health && <View style={s.card}>
      <Text style={s.fieldLabel}>Provider status</Text>
      <Text style={common.body}>Gemini: {health.geminiReady ? 'configured for free use' : 'setup needed'}</Text>
      <Text style={common.body}>Jev: {health.jevReady ? 'promotional access configured' : 'off — embedding search available'}</Text>
      <Text style={s.footnote}>Text-model usage this server session: {health.usage.inputTokens.toLocaleString()} input / {health.usage.outputTokens.toLocaleString()} output tokens. Embedding usage is not included. This is not a billing statement.</Text>
      {health.lastProviderError && <Notice text={health.lastProviderError.message} />}
    </View>}
    <Text style={common.label}>YOUR DATA</Text>
    <Text style={common.body}>Only previews of explicitly selected photos leave the phone, after your consent. Google’s free tier may use submissions to improve its products. Use non-sensitive test photos.</Text>
    <Text style={common.body}>The app keeps a private copy of each selection so it survives restarts. Deleting an original from Photos does not delete this copy. Remove it here to clear it from the app.</Text>
    <Button label={library.consent ? 'Turn off cloud analysis' : 'Cloud analysis is off'} secondary disabled={!library.consent || Boolean(library.activity)} onPress={() => { void library.revokeConsent().catch(() => setMessage('Could not save this setting.')); }} icon="cloud-offline-outline" />
    <Button label="Delete collection & search index" secondary disabled={Boolean(library.activity) || !library.photos.length} onPress={clear} icon="trash-outline" />
    {!!library.notice && <Notice text={library.notice} />}
    <Text style={s.footnote}>Captured by Prompt · Developer prototype · Weeks 2–3{ '\n' }No accounts, subscriptions, or public sharing.</Text>
  </ScrollView></KeyboardAvoidingView>;
}
const s = StyleSheet.create({
  content: { padding: 24, paddingBottom: 50, gap: 15 }, card: { backgroundColor: colors.light, borderRadius: 20, padding: 18, gap: 12 },
  row: { flexDirection: 'row', alignItems: 'center', gap: 10 }, title: { color: colors.ink, fontSize: 17, fontWeight: '600', flex: 1 },
  fieldLabel: { color: colors.ink, fontWeight: '600', fontSize: 14 }, footnote: { color: colors.muted, fontSize: 12, lineHeight: 19 },
});
